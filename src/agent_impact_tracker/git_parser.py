def find_agent_commits(commits: List[GitCommit], agent_patterns: Optional[List[re.Pattern]] = None) -> List[GitCommit]:
    """
    Filter commits whose message or author matches agent signature patterns.
    """
    if agent_patterns is None:
        agent_patterns = [
            re.compile(r'AI[- ]?Agent', re.IGNORECASE),
            re.compile(r'Copilot', re.IGNORECASE),
            re.compile(r'Generated by', re.IGNORECASE),
            re.compile(r'Created by', re.IGNORECASE),
            re.compile(r'agent', re.IGNORECASE),
        ]
    agent_commits = []
    for commit in commits:
        for pattern in agent_patterns:
            if pattern.search(commit.message) or pattern.search(commit.author):
                agent_commits.append(commit)
                break
    return agent_commits
