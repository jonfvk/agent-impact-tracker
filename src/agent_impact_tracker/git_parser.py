import os
import re
from typing import List, Dict, Optional

class GitCommit:
    def __init__(self, commit_hash: str, author: str, date: str, message: str, files: List[str]):
        self.commit_hash = commit_hash
        self.author = author
        self.date = date
        self.message = message
        self.files = files

    def to_dict(self) -> Dict:
        return {
            'commit_hash': self.commit_hash,
            'author': self.author,
            'date': self.date,
            'message': self.message,
            'files': self.files
        }

def parse_git_log(repo_path: str) -> List[GitCommit]:
    """
    Parse the local git log for commit metadata if .git directory exists.
    Only parses the log if the repo_path contains a .git directory.
    
    Returns a list of GitCommit objects.
    """
    git_dir = os.path.join(repo_path, '.git')
    log_path = os.path.join(git_dir, 'logs', 'HEAD')
    if not os.path.isdir(git_dir) or not os.path.isfile(log_path):
        return []

    commits = []
    with open(log_path, 'r', encoding='utf-8', errors='replace') as f:
        lines = f.readlines()

    # Each line in .git/logs/HEAD is:
    # <old-sha> <new-sha> <author> <date> <tz> <message>
    # We'll try to extract new-sha, author, date, and message.
    for line in lines:
        # Example line:
        # 000000... 123456... John Doe <john@example.com> 1700000000 +0000 commit: Initial commit
        m = re.match(r'\S+ (\S+) (.+?) <.+?> (\d+) [+-]\d+\s+(.*)', line)
        if m:
            commit_hash = m.group(1)
            author = m.group(2)
            timestamp = m.group(3)
            message = m.group(4)
            # Convert timestamp to ISO date
            try:
                from datetime import datetime
                date = datetime.utcfromtimestamp(int(timestamp)).isoformat()
            except Exception:
                date = timestamp
            # We can't get files from logs/HEAD, so leave empty for now
            files = []
            commits.append(GitCommit(commit_hash, author, date, message, files))
    return commits

