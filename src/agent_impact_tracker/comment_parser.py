import re
from typing import List, Dict, Optional

AGENT_SIGNATURE_PATTERNS = [
    # Common Copilot signature
    re.compile(r"AI[- ]?Agent:? ?([\w\- ]+)?", re.IGNORECASE),
    re.compile(r"Generated by ([\w\- ]+AI|AI agent)", re.IGNORECASE),
    re.compile(r"Created by ([\w\- ]+AI|AI agent)", re.IGNORECASE),
    re.compile(r"# ?AI[- ]?Agent:? ?([\w\- ]+)?", re.IGNORECASE),
    re.compile(r"# ?Generated by ([\w\- ]+AI|AI agent)", re.IGNORECASE),
    re.compile(r"# ?Created by ([\w\- ]+AI|AI agent)", re.IGNORECASE),
    # General agent signature
    re.compile(r"agent:? ?([\w\- ]+)?", re.IGNORECASE),
]

def extract_agent_signatures_from_comments(
    file_content: str
) -> List[Dict[str, Optional[str]]]:
    """
    Extract agent signatures from code comments in the given Python file content.

    Args:
        file_content (str): The content of a Python file.

    Returns:
        List[Dict[str, Optional[str]]]: List of dicts with 'line', 'signature', and 'agent_name' (if available).
    """
    results = []
    lines = file_content.splitlines()
    for idx, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith('#') or stripped.startswith('"""') or stripped.startswith("'''"):
            for pattern in AGENT_SIGNATURE_PATTERNS:
                match = pattern.search(stripped)
                if match:
                    agent_name = match.group(1).strip() if match.lastindex and match.group(1) else None
                    results.append({
                        'line_number': idx + 1,
                        'line': line,
                        'signature': match.group(0),
                        'agent_name': agent_name
                    })
                    break  # Only match first pattern per line
    return results
